CREATE TABLE IF NOT EXISTS public.perfiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  correo TEXT NOT NULL UNIQUE,
  nombre_completo TEXT NOT NULL,
  carnet TEXT NOT NULL,
  carrera TEXT NOT NULL,
  foto_url TEXT,
  rol TEXT NOT NULL DEFAULT 'Estudiante' CHECK (rol IN ('Estudiante', 'Administrador'))
);

CREATE TABLE IF NOT EXISTS public.equipos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  descripcion TEXT NOT NULL,
  imagen_url TEXT NOT NULL,
  disponible BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.prestamos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
  equipo_id BIGINT NOT NULL REFERENCES public.equipos(id) ON DELETE CASCADE,
  fecha_prestamo DATE NOT NULL DEFAULT CURRENT_DATE,
  fecha_devolucion DATE NOT NULL DEFAULT (CURRENT_DATE + INTERVAL '3 days'),
  estado TEXT NOT NULL DEFAULT 'Pendiente'
    CHECK (estado IN ('Pendiente', 'Aprobado', 'Rechazado', 'Devuelto'))
);

-- Regla de negocio en el backend para validar disponibilidad y actualizar el equipo
CREATE OR REPLACE FUNCTION public.fn_validar_prestamo()
RETURNS TRIGGER AS $$
DECLARE
  v_disponible BOOLEAN;
BEGIN
  IF NEW.fecha_devolucion < NEW.fecha_prestamo THEN
    RAISE EXCEPTION 'La fecha de devolucion no puede ser menor a la fecha de prestamo';
  END IF;

  IF TG_OP = 'INSERT' THEN
    SELECT disponible INTO v_disponible FROM public.equipos WHERE id = NEW.equipo_id;
    IF v_disponible IS FALSE THEN
      RAISE EXCEPTION 'El equipo no esta disponible para prestamo';
    END IF;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    IF NEW.estado = 'Aprobado' AND OLD.estado <> 'Aprobado' THEN
      SELECT disponible INTO v_disponible FROM public.equipos WHERE id = NEW.equipo_id;
      IF v_disponible IS FALSE THEN
        RAISE EXCEPTION 'El equipo ya se encuentra prestado';
      END IF;
      UPDATE public.equipos SET disponible = FALSE WHERE id = NEW.equipo_id;
    END IF;

    IF OLD.estado = 'Aprobado' AND (NEW.estado = 'Devuelto' OR NEW.estado = 'Rechazado') THEN
      UPDATE public.equipos SET disponible = TRUE WHERE id = NEW.equipo_id;
    END IF;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_validar_prestamo ON public.prestamos;
CREATE TRIGGER trg_validar_prestamo
BEFORE INSERT OR UPDATE ON public.prestamos
FOR EACH ROW
EXECUTE FUNCTION public.fn_validar_prestamo();

ALTER TABLE public.perfiles DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.equipos DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.prestamos DISABLE ROW LEVEL SECURITY;

